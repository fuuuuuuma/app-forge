import { readFile, writeFile, mkdir, cp, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { platformNames } from '../lib/brief.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const ideas = JSON.parse(await readFile(path.join(root,'catalog/ideas.json'),'utf8'));
const escape = value => String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
if(ideas.length!==100) throw new Error('100件のカタログが必要です');
const dist=path.join(root,'dist');
await mkdir(dist,{recursive:true});
const cards=ideas.map(idea=>`<article class="idea-card" data-card="${idea.id}"><div class="card-visual visual-${idea.platform}"><span class="card-index">NO. ${idea.id}</span><span class="visual-symbol" aria-hidden="true">${idea.platform==='web'?'↗':idea.platform==='mobile'?'a':'＋'}</span><button class="save-idea" data-id="${idea.id}" data-title="${escape(idea.title)}" aria-pressed="false" aria-label="${escape(idea.title)}を気になるに保存">♡</button></div><div class="card-content"><div class="card-tags"><span>${escape(idea.category)}</span><span>${platformNames[idea.platform]}</span></div><h3>${escape(idea.title)}</h3><p class="summary">${escape(idea.summary)}</p><div class="card-bottom"><span class="level">${escape(idea.level)}</span><button class="open-idea" data-open="${idea.id}" aria-label="${escape(idea.title)}の制作を始める">このアプリを作る ↗</button></div></div></article>`).join('\n');
let html=await readFile(path.join(root,'site/index.html'),'utf8');
html=html.replace('<!--IDEA_CARDS-->',cards);
if(!html.includes('data-card="100"'))throw new Error('カタログの埋め込みに失敗');
await writeFile(path.join(dist,'index.html'),html);
for(const file of await readdir(path.join(root,'site')))if(file!=='index.html')await cp(path.join(root,'site',file),path.join(dist,file));
await cp(path.join(root,'lib/brief.mjs'),path.join(dist,'brief.mjs'));
await cp(path.join(root,'catalog/ideas.json'),path.join(dist,'ideas.json'));
const assets=path.join(root,'plugins/app-forge/skills/app-forge/assets');
await mkdir(assets,{recursive:true});
await cp(path.join(root,'catalog/ideas.json'),path.join(assets,'ideas.json'));
console.log(`100件を静的ページとスキルへ収録しました: ${dist}`);
